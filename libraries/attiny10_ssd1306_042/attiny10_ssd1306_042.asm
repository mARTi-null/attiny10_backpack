************************************************************************************************************************
LIST OF OLED COMMANDS
************************************************************************************************************************

	-----OLED INIT COMMANDS-----
	0xAE				; Oled OFF
	0xD5, 0xF0			; Oled freq/divider
	0xA8, 0x27			; Multyplex Ratio 1/40 duty
	0xAD, 0x30			; Set internal IREF
	0xC8				; Scan direction, default scan C0
	0xA1				; Segment remap, default no remap A0
	0x20, 0x00			; Set Addressing mode (0x00 - Horizontal, 0x01 - Vertical, (default)0x02 - Page Addressing mode)
	0x21, 0x1C, 0x63	; Set Column address |||||||| with offset of 28
	0x22, 0x00, 0x04	; Set page address _ _ _ _
	0xDA, 0x12			; Set COM pins to sequential
	0x81, 0xAF			; Set contrast
	0xD9, 0x22			; Set precharge level F1/22
	0x8D, 0x14			; Set Charge pump enable
	0xA4				; A5 Full ON, A4 ON
	0xAF				; Oled ON

