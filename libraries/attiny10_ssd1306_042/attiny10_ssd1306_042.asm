/************************************************************************************************************************
OLED INITIALIZATION
***********************************************************************************************************************/
init_oled:
	ldi 	R19, 27									; Number of commands to send in array
	ldi		ZL, low(0x4000 + oled_commands * 2)		;
	ldi		ZH, high(0x4000 + oled_commands *2)
	rcall	start_command
send_command:
	ld		i2c_data, Z+
	rcall	i2c_send
	dec		R19
	brne	send_command
	rcall	i2c_stop
	nop
	nop
ret

/***********************************************************************************************************************
OLED I2C PROTOCOL
***********************************************************************************************************************/
start_command:
	rcall	i2c_start
	ldi		i2c_data, oled_addr
	rcall	i2c_send
	ldi		i2c_data, oled_command
	rcall	i2c_send
ret

start_data:
	rcall	i2c_start
	ldi		i2c_data, oled_addr
	rcall	i2c_send
	ldi		i2c_data, oled_i2c_data
	rcall	i2c_send
ret

/***********************************************************************************************************************
CLEAR SCREEN
***********************************************************************************************************************/
clear_screen:
	ldi		count_j, 0x02
clr_outer:
	ldi		count_i, 0xB4
clr_inner:
	ldi		i2c_data, 0x00
	rcall	i2c_send
	dec		count_i
	brne	clr_inner
	dec		count_j
	brne	clr_outer
ret

/***********************************************************************************************************************
SET CURSOR
***********************************************************************************************************************/
set_cursor:
	rcall	i2c_stop
	rcall	start_command
	ldi		i2c_data, 0x21
	rcall	i2c_send
	mov		i2c_data, x1		; Start column
	rcall	i2c_send
	mov		i2c_data, x2		; End column
	rcall	i2c_send
	ldi		i2c_data, 0x22
	rcall	i2c_send
	mov		i2c_data, y1		; Start page
	rcall	i2c_send
	mov		i2c_data, y2		; End page
	rcall	i2c_send
	rcall	i2c_stop
ret

/***********************************************************************************************************************
DRAW SINGLE ASCII CHAR FROM FONT ARRAY
***********************************************************************************************************************/
draw_char:
	rcall	get_char_pos
	ldi		r21, 0x00
	ldi		ZL, low(0x4000 + font * 2)
	ldi		ZH, high(0x4000 + font * 2)
	add		ZL, tmp
	adc		ZH, r21
	ldi		count_j, font_width
loop_text:
	ld		i2c_data, Z+
	rcall	i2c_send
	dec		count_j
	brne	loop_text
	ldi		i2c_data, 0x00
	rcall	i2c_send
ret

